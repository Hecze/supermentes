-- Las tablas de la cuenta de la docente en Postgres (Neon). Se puede correr varias veces:
--   npm run db:postgres
-- Fechas en TEXT (ISO): las consultas de api/ las comparan como texto.

CREATE TABLE IF NOT EXISTS envios (
  docente TEXT NOT NULL,
  codigo TEXT NOT NULL,
  clave TEXT NOT NULL,
  juego TEXT NOT NULL,
  tema TEXT NOT NULL DEFAULT '',
  grado TEXT,
  practica TEXT,
  fecha TEXT NOT NULL,
  PRIMARY KEY (docente, codigo)
);
CREATE INDEX IF NOT EXISTS envios_por_fecha ON envios (docente, fecha DESC);

CREATE TABLE IF NOT EXISTS docentes (
  id TEXT PRIMARY KEY,
  nombre TEXT NOT NULL,
  colegio TEXT,
  grado TEXT NOT NULL,
  creado TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS salones (
  id TEXT PRIMARY KEY,
  docente TEXT NOT NULL,
  grado TEXT NOT NULL,
  seccion TEXT NOT NULL,
  creado TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS salones_por_docente ON salones (docente);

CREATE TABLE IF NOT EXISTS alumnos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salon TEXT NOT NULL REFERENCES salones (id) ON DELETE CASCADE,
  nombre TEXT NOT NULL,
  orden INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS alumnos_por_salon ON alumnos (salon, orden);

CREATE TABLE IF NOT EXISTS tareas (
  codigo TEXT PRIMARY KEY,
  docente TEXT NOT NULL,
  salon TEXT NOT NULL REFERENCES salones (id) ON DELETE CASCADE,
  tema TEXT NOT NULL,
  area TEXT NOT NULL DEFAULT '',
  desempeno TEXT NOT NULL DEFAULT '',
  juego TEXT NOT NULL,
  segundos INTEGER NOT NULL,
  vence TEXT NOT NULL,
  creado TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS tareas_por_docente ON tareas (docente, creado DESC);

CREATE TABLE IF NOT EXISTS intentos (
  tarea TEXT NOT NULL REFERENCES tareas (codigo) ON DELETE CASCADE,
  alumno INTEGER NOT NULL REFERENCES alumnos (id) ON DELETE CASCADE,
  aciertos INTEGER NOT NULL,
  total INTEGER NOT NULL,
  segundos INTEGER NOT NULL,
  salidas INTEGER NOT NULL DEFAULT 0,
  respuestas TEXT NOT NULL,
  fecha TEXT NOT NULL,
  PRIMARY KEY (tarea, alumno)
);
